// Global helper to load data from localStorage or fallback to defaults
window.getSSVPData = function() {
  const saved = localStorage.getItem('SSVP_DATA');
  if (saved) {
    try {
      return JSON.parse(saved);
    } catch(e) {
      console.error("Error parsing local SSVP data", e);
    }
  }
  return window.SSVP_DATA;
};
